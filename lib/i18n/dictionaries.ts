export function loadDictionary(locale: string | null | undefined) {
  const normalizedLocale = isLocale(locale) ? locale : defaultLocale;
  return {
    ...en,
    ...languageOverrides[normalizedLocale],
  };
}

export function createTranslator(locale: string | null | undefined) {
  const dictionary = loadDictionary(locale);

  return function t(key: string) {
    return dictionary[key] ?? en[key] ?? key;
  };
}
